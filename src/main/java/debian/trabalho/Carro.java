package debian.trabalho;

public class Carro {

    String modelo;
    String marca;
    int ano;
    String placa;
    double valorDiaria;

    public Carro(String modelo, String marca, int ano, String placa, double valorDiaria) {

        this.modelo = modelo;
        this.marca = marca;
        this.ano = ano;
        this.placa = placa;
        this.valorDiaria = valorDiaria;
    }
}
